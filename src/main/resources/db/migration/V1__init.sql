-- from now on schema changes go throught new versioned migration files(V2, V3 ...)


create table users
(
    id       bigint generated by default as identity,
    username varchar(255) not null unique,
    email    varchar(255) not null unique,
    password varchar(255) not null,
    role     varchar(255),
    primary key (id)
);

create table project
(
    id          bigint generated by default as identity,
    name        varchar(255) not null,
    description varchar(255),
    created_at  timestamp(6),
    owner_id    bigint       not null,
    primary key (id)
);

create table task
(
    id          bigint generated by default as identity,
    title       varchar(255) not null,
    description varchar(255),
    status      varchar(255),
    priority    varchar(255),
    created_at  timestamp(6),
    due_date    timestamp(6),
    project_id  bigint       not null,
    assigned_to bigint,
    primary key (id)
);

create table comment
(
    id         bigint generated by default as identity,
    text       varchar(255) not null,
    created_at timestamp(6),
    task_id    bigint       not null,
    user_id    bigint       not null,
    primary key (id)
);

alter table project
    add constraint fk_project_owner foreign key (owner_id) references users;
alter table task
    add constraint fk_task_project foreign key (project_id) references project;
alter table task
    add constraint fk_task_assigned_to foreign key (assigned_to) references users;
alter table comment
    add constraint fk_comment_task foreign key (task_id) references task;
alter table comment
    add constraint fk_comment_user foreign key (user_id) references users;
